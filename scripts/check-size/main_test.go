func seed(t *testing.T, files map[string]string, baseline string) string {
	t.Helper()
	root := t.TempDir()
	write(t, root, "go.mod", "module saundo\n")
	for rel, src := range files {
		write(t, root, rel, src)
	}
	if baseline != "" {
		write(t, root, baselinePath, baseline)
	}
	return root
}

func write(t *testing.T, root, rel, src string) {
	t.Helper()
	path := filepath.Join(root, rel)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(src), 0o600); err != nil {
		t.Fatal(err)
	}
}

// lines generates n code lines, so the fixture exercises the code-line count
// rather than the comment-only lines the gate now ignores.
func lines(n int) string {
	var b strings.Builder
	for i := 0; i < n; i++ {
		fmt.Fprintf(&b, "var x%d = %d\n", i, i)
	}
	return b.String()
}

func TestMissingBaselineFailsClosed(t *testing.T) {
	root := seed(t, nil, "")
	if err := run(root); err == nil {
		t.Fatal("a missing baseline passed; the gate must fail closed")
	}
}

func TestBaselineFileAtLimitPasses(t *testing.T) {
	root := seed(t, map[string]string{
		"internal/engine/engine.go": lines(10),
	}, "internal/engine/engine.go\t10\n")
	if err := run(root); err != nil {
		t.Fatalf("at-limit file: %v", err)
	}
}

func TestBaselineFileOverLimitFails(t *testing.T) {
	root := seed(t, map[string]string{
		"internal/engine/engine.go": lines(11),
	}, "internal/engine/engine.go\t10\n")
	err := run(root)
	if err == nil || !strings.Contains(err.Error(), "above its 10-line baseline") {
		t.Fatalf("grown file = %v, want a baseline violation", err)
	}
}

